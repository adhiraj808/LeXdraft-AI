"""Business logic layer for case processing."""

import asyncio
import logging
import uuid
from datetime import datetime, timedelta, timezone
from typing import Any, List, Optional

from sqlalchemy import select, update
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy.orm import load_only, selectinload

from app.core.config import settings
from app.db.redis_client import (
    cache_case_data,
    cache_draft,
    delete_case_cache,
    get_draft,
    publish_progress,
    update_case_status,
)
from app.models.case import Case, Draft
from app.models.user import User
from app.schemas.case import (
    MAX_DESCRIPTION_CHARS,
    MAX_RELIEF_CHARS,
    SECTION_NAMES,
    CaseSubmit,
)

logger = logging.getLogger(__name__)

# How many drafts may run the NLP pipeline at the same time (memory and LLM rate limits).
_processing_semaphore = asyncio.Semaphore(max(1, settings.MAX_CONCURRENT_DRAFTS))


def _model_name(nlp_pipeline) -> str:
    """Human-readable label for which generator produced a draft."""
    gen = getattr(nlp_pipeline, "generator", None)
    if gen is None:
        return "unknown"
    label = getattr(gen, "model_label", None)
    if label:
        return label
    if getattr(gen, "_provider", None):
        return gen._provider
    if getattr(gen, "use_model", False):
        return "local-llm"
    return "template"


def _clip(value: Any, limit: int) -> Optional[str]:
    """Coerce an LLM-supplied value to a stripped string of at most `limit` chars (None if empty).

    Model output is untrusted: it may be a list, a number, or far longer than the database column.
    """
    if value is None:
        return None
    if isinstance(value, (list, tuple)):
        value = ", ".join(str(item) for item in value if item)
    text = str(value).strip()
    return text[:limit] or None


async def recover_stale_cases(
    session_factory=None, max_age_minutes: Optional[int] = None
) -> int:
    """Mark cases stuck in pending/processing as failed.

    Drafts are generated by in-process background tasks. When the server restarts, the tasks
    die with it and their cases would otherwise stay "processing" forever (the UI polls them
    endlessly). Only cases untouched for `max_age_minutes` are touched, so a case that another
    worker is processing right now is left alone.
    """
    if session_factory is None:
        from app.db.postgres import AsyncSessionLocal as session_factory
    age = settings.STALE_CASE_MINUTES if max_age_minutes is None else max_age_minutes
    cutoff = datetime.now(timezone.utc).replace(tzinfo=None) - timedelta(minutes=age)
    async with session_factory() as db:
        result = await db.execute(
            update(Case)
            .where(Case.status.in_(("pending", "processing")), Case.updated_at < cutoff)
            .values(status="failed")
        )
        await db.commit()
        count = result.rowcount or 0
    if count:
        logger.warning(
            f"Marked {count} stale case(s) as failed (interrupted by a restart)."
        )
    return count


class CaseService:
    def __init__(self, db: AsyncSession):
        self.db = db

    async def create_case(self, payload: CaseSubmit, user: User) -> Case:
        """Create a new case record and cache the input in Redis."""
        case = Case(
            id=str(uuid.uuid4()),
            user_id=user.id,
            title=payload.title,
            jurisdiction=payload.jurisdiction,
            petitioner_name=payload.petitioner_name,
            respondent_name=payload.respondent_name,
            incident_date=payload.incident_date,
            case_description=payload.case_description,
            sections_alleged=payload.sections_alleged,
            relief_sought=payload.relief_sought,
            status="pending",
        )
        self.db.add(case)
        await self.db.commit()

        # Cache input for fast pipeline access (best-effort: PostgreSQL is the source of truth).
        await cache_case_data(
            case.id,
            {
                "title": payload.title,
                "jurisdiction": payload.jurisdiction or "",
                "petitioner_name": payload.petitioner_name or "",
                "respondent_name": payload.respondent_name or "",
                "incident_date": payload.incident_date or "",
                "case_description": payload.case_description,
                "sections_alleged": payload.sections_alleged or "",
                "relief_sought": payload.relief_sought or "",
                "status": "pending",
            },
        )
        return case

    async def create_case_from_prompt(self, prompt: str, user: User) -> Case:
        """Create a case from a free-form prompt using LLM field extraction."""
        from app.nlp.extractor import extract_case_fields

        fields = await asyncio.to_thread(extract_case_fields, prompt) or {}

        description = _clip(fields.get("case_description"), MAX_DESCRIPTION_CHARS)
        if not description or len(description) < 30:
            description = prompt
        title = _clip(fields.get("title"), 500)
        if not title or len(title) < 5:
            title = prompt[:57] + "..."

        # Every value is clipped to its column size: an over-long model answer must not turn
        # into a database error.
        payload = CaseSubmit(
            title=title,
            jurisdiction=_clip(fields.get("jurisdiction"), 200),
            petitioner_name=_clip(fields.get("petitioner_name"), 300),
            respondent_name=_clip(fields.get("respondent_name"), 300),
            incident_date=_clip(fields.get("incident_date"), 50),
            case_description=description,
            sections_alleged=_clip(fields.get("sections_alleged"), 500),
            relief_sought=_clip(fields.get("relief_sought"), MAX_RELIEF_CHARS),
        )
        return await self.create_case(payload, user)

    async def process_case(
        self, case_id: str, nlp_pipeline, strict: bool = False
    ) -> Case:
        """Run the NLP pipeline on a case and persist results.

        strict=True (AI-chat flow): no template fallback - if the model
        can't generate, the case is marked 'failed' and no draft is stored.
        """
        # Limit concurrent draft generation to control memory usage
        async with _processing_semaphore:
            result = await self.db.execute(select(Case).where(Case.id == case_id))
            case = result.scalar_one_or_none()
            if not case:
                raise ValueError(f"Case {case_id} not found")

            try:
                case.status = "processing"
                await self.db.commit()
                await update_case_status(case_id, "processing")
                await publish_progress(case_id, "preprocessing")

                case_input = {
                    "title": case.title,
                    "case_description": case.case_description,
                    "petitioner_name": case.petitioner_name,
                    "respondent_name": case.respondent_name,
                    "incident_date": case.incident_date,
                    "jurisdiction": case.jurisdiction,
                    "relief_sought": case.relief_sought,
                }

                # Run full NLP pipeline (no DB connection is held while this runs: the commit
                # above released it).
                pipeline_result = await nlp_pipeline.process(case_input, strict=strict)

                await publish_progress(case_id, "saving_results")

                # Persist NLP outputs to PostgreSQL
                classification = pipeline_result["classification"]
                case.case_type = classification["case_type"]
                case.case_type_confidence = classification["confidence"]
                case.extracted_entities = pipeline_result["entities"]
                case.status = "completed"

                draft_sections = pipeline_result["draft_sections"]
                gen_time = draft_sections.pop("_generation_time", None)
                full_text = draft_sections.pop("_full_text", None)
                # What actually wrote the text (an LLM, a template, or a mix) - not just what is configured.
                model_used = (
                    draft_sections.pop("_model_used", None) or _model_name(nlp_pipeline)
                )[:100]

                # Upsert draft
                draft_result = await self.db.execute(
                    select(Draft).where(Draft.case_id == case_id)
                )
                existing_draft = draft_result.scalar_one_or_none()

                if existing_draft:
                    existing_draft.sections = draft_sections
                    existing_draft.full_text = full_text
                    existing_draft.version += 1
                    existing_draft.generation_time_seconds = gen_time
                    existing_draft.model_used = model_used
                else:
                    self.db.add(
                        Draft(
                            case_id=case_id,
                            sections=draft_sections,
                            full_text=full_text,
                            version=1,
                            model_used=model_used,
                            generation_time_seconds=gen_time,
                        )
                    )

                await self.db.commit()
                await self.db.refresh(case)

                # Cache draft in Redis (best-effort - a cache outage must not fail a finished draft)
                await cache_draft(
                    case_id,
                    {
                        "sections": draft_sections,
                        "full_text": full_text,
                    },
                )
                await update_case_status(case_id, "completed")
                await publish_progress(case_id, "completed")

                return case

            except Exception:
                logger.exception(f"Pipeline failed for case {case_id}")
                await self._mark_failed(case_id)
                raise

    async def _mark_failed(self, case_id: str) -> None:
        try:
            # The session may be in a failed state (e.g. a commit error): reset it first.
            await self.db.rollback()
            await self.db.execute(
                update(Case).where(Case.id == case_id).values(status="failed")
            )
            await self.db.commit()
        except Exception:
            logger.exception(f"Could not mark case {case_id} as failed")
        await update_case_status(case_id, "failed")
        await publish_progress(case_id, "failed")

    async def get_case(self, case_id: str, user: User) -> Optional[Case]:
        result = await self.db.execute(
            select(Case)
            .options(selectinload(Case.draft))
            .where(Case.id == case_id, Case.user_id == user.id)
        )
        return result.scalar_one_or_none()

    async def list_cases(
        self, user: User, skip: int = 0, limit: int = 20
    ) -> List[Case]:
        # Only the columns the list view shows: loading every row's full description and
        # extracted entities just to render titles wastes memory and bandwidth.
        result = await self.db.execute(
            select(Case)
            .options(
                load_only(
                    Case.id, Case.title, Case.case_type, Case.status, Case.created_at
                )
            )
            .where(Case.user_id == user.id)
            .order_by(Case.created_at.desc())
            .offset(skip)
            .limit(limit)
        )
        return list(result.scalars().all())

    async def delete_case(self, case_id: str, user: User) -> bool:
        result = await self.db.execute(
            select(Case)
            .options(selectinload(Case.draft))
            .where(Case.id == case_id, Case.user_id == user.id)
        )
        case = result.scalar_one_or_none()
        if not case:
            return False
        await self.db.delete(case)
        await self.db.commit()
        await delete_case_cache(case_id)
        return True

    async def regenerate_section(
        self,
        case_id: str,
        section: str,
        user: User,
        nlp_pipeline,
        additional_context: str = None,
    ) -> dict:
        """Regenerate a specific section of an existing draft."""
        if section != "all" and section not in SECTION_NAMES:
            raise ValueError(f"Unknown section: {section}")

        case = await self.get_case(case_id, user)
        if not case:
            raise ValueError("Case not found")

        if section == "all":
            await self.process_case(case_id, nlp_pipeline)
            regenerated = await self.get_case(case_id, user)
            if not regenerated or not regenerated.draft:
                raise RuntimeError("Draft regeneration did not produce a draft")
            return {
                "section": "all",
                "sections": regenerated.draft.sections,
                "full_text": regenerated.draft.full_text,
                "version": regenerated.draft.version,
            }

        case_input = {
            "title": case.title,
            "case_description": case.case_description,
            "petitioner_name": case.petitioner_name,
            "respondent_name": case.respondent_name,
            "incident_date": case.incident_date,
            "jurisdiction": case.jurisdiction,
            "relief_sought": case.relief_sought,
        }

        new_content = await nlp_pipeline.regenerate_section(
            section=section,
            case_input=case_input,
            entities=case.extracted_entities or {},
            classification={"case_type": case.case_type or "Civil"},
            additional_context=additional_context,
        )

        # Update draft
        if case.draft:
            sections = dict(case.draft.sections)
            sections[section] = new_content
            case.draft.sections = sections
            case.draft.version += 1
            await self.db.commit()

            # Update cache
            cached = await get_draft(case_id) or {}
            cached_sections = cached.get("sections", {})
            cached_sections[section] = new_content
            await cache_draft(
                case_id,
                {"sections": cached_sections, "full_text": cached.get("full_text", "")},
            )

        return {"section": section, "content": new_content}
